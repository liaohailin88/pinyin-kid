def norm_py(py):
    """校验拼音：只允许字母 + ü + 声调符号"""
    return re.fullmatch(r"[a-züāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ]+", py) is not None


def strip_tone(py):
    # 去声调但保留 ü（不要写成 v，否则 applyTone 还原不出 ǜ）
    table = str.maketrans('āáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜ',
                          'aaaaeeeeiiiioooouuuuüüüü')
    return py.translate(table)


def tone_of(py):
    table = {'ā': 1, 'á': 2, 'ǎ': 3, 'à': 4, 'ē': 1, 'é': 2, 'ě': 3, 'è': 4,
             'ī': 1, 'í': 2, 'ǐ': 3, 'ì': 4, 'ō': 1, 'ó': 2, 'ǒ': 3, 'ò': 4,
             'ū': 1, 'ú': 2, 'ǔ': 3, 'ù': 4, 'ǖ': 1, 'ǘ': 2, 'ǚ': 3, 'ǜ': 4}
    for ch in py:
        if ch in table:
            return table[ch]
    return 0


def is_hanzi(ch):
    return '\u4e00' <= ch <= '\u9fff'


def main():
    errors = []
    units = []
    seen = {}
    total = 0

    for uid, title, book, lessons, rows in LESSON_PLAN:
        char_list = []
        lesson_meta = []
        for lname, start, end in lessons:
            block = rows[start:end]
            if not block:
                errors.append('课次为空: %s / %s' % (title, lname))
                continue
            in_lesson = []
            for row in block:
                if len(row) < 3:
                    errors.append('行数据不足: %r' % (row,))
                    continue
                ch, py, word = row[0], row[1], row[2]
                tip = row[3] if len(row) > 3 else ''
                if not is_hanzi(ch) or len(ch) != 1:
                    errors.append('非法汉字: %r' % (ch,))
                if not norm_py(py):
                    errors.append('非法拼音: %s %s' % (ch, py))
                if ch in seen:
                    info = seen[ch]
                    if py not in info['pys']:
                        info['pys'].append(py)      # 多音字记录
                    if ch not in in_lesson:
                        in_lesson.append(ch)
                    continue
                item = {
                    'c': ch,
                    'p': py,
                    't': tone_of(py),
                    'sb': strip_tone(py),
                    'w': word,
                    'u': uid,
                    'l': lname,
                }
                if tip:
                    item['m'] = tip
                seen[ch] = {'c': ch, 'p': py, 't': tone_of(py), 'sb': strip_tone(py),
                            'w': word, 'u': uid, 'l': lname, 'pys': [py], 'm': tip}
                char_list.append(ch)
                in_lesson.append(ch)
                total += 1
            lesson_meta.append({'name': lname, 'chars': in_lesson})
        units.append({'id': uid, 'title': title, 'book': book,
                      'desc': ' / '.join(l['name'] for l in lesson_meta),
                      'lessons': lesson_meta, 'chars': char_list})

    # 补齐《写字表》遗漏字（见 WRITE_EXTRA 注释）
    for ch, py, word, uid in WRITE_EXTRA:
        if ch in seen:
            continue
        if uid == 'wx':
            u = next((x for x in units if x['id'] == 'wx'), None)
            if u is None:
                u = {'id': 'wx', 'title': '一年级下册 · 写字表补充', 'book': '下册',
                     'desc': '官方《写字表》有、课文清单未覆盖的字（单独标注，非课文生字）',
                     'lessons': [{'name': '写字表补充', 'chars': []}], 'chars': []}
                units.append(u)
        else:
            u = next(x for x in units if x['id'] == uid)
            if not any(l['name'] == '写字表补充' for l in u['lessons']):
                u['lessons'].append({'name': '写字表补充', 'chars': []})
        lname = '写字表补充'
        item = {'c': ch, 'p': py, 't': tone_of(py), 'sb': strip_tone(py),
                'w': word, 'u': u['id'], 'l': lname}
        seen[ch] = dict(item, pys=[py])
        u['chars'].append(ch)
        next(l for l in u['lessons'] if l['name'] == lname)['chars'].append(ch)
        total += 1

    # 写字表标记
    write_set = set(''.join(S1_WRITE) + ''.join(S2_WRITE))
    all_chars = []
    for info in seen.values():
        item = {k: v for k, v in info.items() if k != 'pys' and v != ''}
        if len(info['pys']) > 1:
            item['alt'] = [p for p in info['pys'] if p != info['p']]
        if info['c'] in write_set:
            item['w100'] = 1
        all_chars.append(item)

    # 检查 hanzi 数据覆盖
    src = os.environ.get('HANZI_SRC', '')
    missing_stroke = []
    if src and os.path.isdir(src):
        for it in all_chars:
            if not os.path.exists(os.path.join(src, it['c'] + '.json')):
                missing_stroke.append(it['c'])

    out = {
        'meta': {
            'version': 1,
            'edition': '部编版（统编版）',
            'count': len(all_chars),
            'writeCount': len([c for c in all_chars if c.get('w100')]),
            'sources': [
                '一年级上册《写字表》100字（官方单元分部原文）',
                '一年级下册《写字表》200字（官方课文顺序原文）',
                '一年级下册《识字表》400字（官方按课分组原文）',
                '一年级上册课文生字（按官方目录逐课整理）',
            ],
            'note': '上册《识字表》300字官方完整清单未取得公开原文，上册按课文生字+写字表合并，另设"常用补充"组并单独标注。',
            'missingStroke': missing_stroke,
        },
        'units': units,
        'chars': all_chars,
        'sentences': [{'py': a, 'cn': b, 'unit': c} for a, b, c in SENTENCES],
    }

    js = ('/* 自动生成：由 scripts/gen_chars.py 编译，请勿手改 */\n'
          'window.CHAR_DB = ' + json.dumps(out, ensure_ascii=False, indent=0).replace('\n', '') + ';\n')
    with open(os.path.join(DATA_DIR, 'characters.js'), 'w', encoding='utf-8') as f:
        f.write(js)

    print('单字总数:', len(all_chars))
    print('必写字数:', out['meta']['writeCount'])
    print('单元数:', len(units))
    print('句子数:', len(SENTENCES))

    # 导出笔顺数据：assets/hanzi/<字>.json（HTTP 下按需取）+ data/hanzi-all.js（file:// 时整体取）
    bulk = {}
    if src and os.path.isdir(src):
        for it in all_chars:
            ch = it['c']
            sp = os.path.join(src, ch + '.json')
            if not os.path.exists(sp):
                continue
            with open(sp, encoding='utf-8') as f:
                raw = json.load(f)
            slim = {'strokes': raw.get('strokes', []), 'medians': raw.get('medians', [])}
            if raw.get('radStrokes'):
                slim['radStrokes'] = raw['radStrokes']
            with open(os.path.join(ASSET_HANZI, ch + '.json'), 'w', encoding='utf-8') as f:
                json.dump(slim, f, ensure_ascii=False, separators=(',', ':'))
            bulk[ch] = slim
        with open(os.path.join(DATA_DIR, 'hanzi-all.js'), 'w', encoding='utf-8') as f:
            f.write('/* 自动生成：由 scripts/gen_chars.py 编译，请勿手改 */\n')
            f.write('window.HANZI_STROKES = ')
            json.dump(bulk, f, ensure_ascii=False, separators=(',', ':'))
            f.write(';\n')
        print('笔顺数据:', len(bulk), '字')
    if missing_stroke:
        print('缺笔画数据:', ''.join(missing_stroke), '(%d)' % len(missing_stroke))
    if errors:
        print('!! 校验错误 %d 条:' % len(errors))
        for e in errors[:40]:
            print('   ', e)
        return 1
    print('校验通过')
    return 0


if __name__ == '__main__':
    sys.exit(main())
